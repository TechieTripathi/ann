      </g>
      <g v-for="n in INPUTS.filter(q => q.click !== null)" :key="'sqc-' + n.k" v-click="n.click">
        <rect :x="n.x - 26" :y="n.y - 26" width="52" height="52" rx="8"
              fill="var(--ann-paper-raised)" stroke="var(--ann-ink-soft)" stroke-width="2" style="opacity:0.85" />
