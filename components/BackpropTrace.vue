<!--
  BackpropTrace.vue — Lecture 2, Chapter 4 (the worked example).

  One 2-2-2 network, seven stages, driven by the `stage` prop. Every number
  comes from the frozen V table below, which is generated by
  scripts/verify-numbers.py and cross-checked against PyTorch autograd.
  If a number here disagrees with that script, THIS FILE is wrong.

  CLICK CONTRACT
  Reveals are absolute v-click indices starting at `from` (default 1).
  This deliberately differs from NeuronDiagram.vue, which starts at
  v-click="2" and so burns the first key press on nothing. Because these
  v-click directives live inside a child component, Slidev cannot auto-count
  them: every slide using this component MUST set `clicks: N` in frontmatter.
  The required N for each stage is printed in STAGES below — read it there,
  do not guess.

  READING THE DIAGRAM (taught once on the setup slide, then relied on)
    above a neuron   = net, the weighted sum        teal   (forward)
    inside a neuron  = out, the activation          ink
    below a neuron   = delta, the blame             ember  (backward)
    chip to the right= bias
    on an edge       = the weight (teal) and, in backward stages,
                       that weight's gradient (ember)
-->
